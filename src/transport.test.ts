import { afterEach, describe, expect, it, vi } from 'vitest'
import { Transport, tempo } from './transport'

afterEach(() => vi.useRealTimers())
describe('sixteenth-note transport', () => {
  it('maps all speed choices to actual BPM', () => {
    expect(['slow','mid','fast'].map(speed => tempo(80, speed as 'slow'|'mid'|'fast'))).toEqual([60,80,100])
    expect(tempo(90,'slow')).toBe(68)
  })
  it('advances once per sixteenth at independently expected times and wraps', () => {
    vi.useFakeTimers()
    const hit = vi.fn(), step = vi.fn()
    const transport = new Transport(globalThis, hit)
    transport.start(120, ['bd','sn','hh','cp'], step)
    vi.advanceTimersByTime(124)
    expect(step).not.toHaveBeenCalled()
    vi.advanceTimersByTime(501)
    expect(step.mock.calls.map(call => call[0])).toEqual([0,1,2,3,0])
    expect(hit.mock.calls.flat()).toEqual(['bd','sn','hh','cp','bd'])
  })
  it.each([[60,250],[120,125],[150,100]])('runs %i BPM with %i ms steps', (bpm, ms) => {
    vi.useFakeTimers()
    const step = vi.fn()
    const transport = new Transport(globalThis, vi.fn())
    transport.start(bpm,['~'],step)
    vi.advanceTimersByTime(ms * 4)
    expect(step).toHaveBeenCalledTimes(4)
  })
  it('repeated start replaces interval and stop cancels subdivisions, including idempotent stop', () => {
    vi.useFakeTimers()
    const hit = vi.fn()
    const transport = new Transport(globalThis, hit)
    transport.start(120,['sn*4'])
    transport.start(120,['sn*4'])
    vi.advanceTimersByTime(125)
    expect(hit).toHaveBeenCalledTimes(1)
    transport.stop()
    transport.stop()
    expect(vi.getTimerCount()).toBe(0)
    vi.advanceTimersByTime(2000)
    expect(hit).toHaveBeenCalledTimes(1)
    transport.start(60,['bd'])
    vi.advanceTimersByTime(250)
    expect(hit.mock.calls.flat()).toEqual(['sn','bd'])
    transport.stop()
  })
  it('does not emit a drum after an onStep callback stops the run', () => {
    vi.useFakeTimers()
    const hit = vi.fn()
    const transport = new Transport(globalThis, hit)
    transport.start(120,['bd'],() => transport.stop())
    vi.advanceTimersByTime(125)
    expect(hit).not.toHaveBeenCalled()
  })
})
